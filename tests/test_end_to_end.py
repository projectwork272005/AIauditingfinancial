"""End-to-end mechanics test: raw log -> coding -> analysis -> figures.

The replies below are generated by a deterministic TEST FIXTURE (a simple
rule plus noise), not by any language model. Everything is written to a
temporary directory supplied by pytest; nothing touches outputs/. The test
checks that the pipeline runs and produces every table and figure; it says
nothing about how real models behave.
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import analysis  # noqa: E402
import code_responses  # noqa: E402
import figures  # noqa: E402
import run_experiment  # noqa: E402

FAKE_RATING = {"Cash": "R1", "Bond": "R2", "Hybrid": "R3", "Equity": "R4", "Commodity": "R4"}


def fixture_menu(path: Path) -> pd.DataFrame:
    menu = pd.read_csv(ROOT / "data" / "fund_menu_candidates.csv", dtype=str).fillna("")
    menu["risk_rating"] = menu["asset_class"].map(FAKE_RATING)      # FAKE ratings for the test only
    menu["menu_status"] = "VERIFIED"
    menu.to_csv(path, index=False)
    return menu


def fixture_reply(task, menu, rng) -> str:
    level = int(task["risk_level"])
    by_class = {c: menu.loc[menu["asset_class"] == c, "code"].tolist() for c in FAKE_RATING}
    target_equity = 15 * level + rng.normal(0, 8)
    picks = [rng.choice(by_class["Cash"]), rng.choice(by_class["Bond"]), rng.choice(by_class["Equity"])]
    w_eq = int(np.clip(target_equity, 0, 90))
    weights = [max(100 - w_eq - 30, 0), 30, w_eq]
    weights[0] += 100 - sum(weights)
    if rng.random() < 0.03:
        return "Sorry, I can only give general guidance."                       # unparseable
    port = [{"code": c, "fund_name": "", "weight_pct": w, "reason": "fixture"} for c, w in zip(picks, weights)]
    if rng.random() < 0.05:
        port.append({"code": "999999", "weight_pct": 5, "reason": "fixture off-menu"})
    obj = {"portfolio": port, "dca_recommended": bool(rng.random() < 0.7), "rebalancing_rule": "yearly",
           "risk_warnings": ["fixture warning"] * int(rng.integers(1, 5)),
           "explanation": "Given the short horizon there is a conflict." if rng.random() < 0.3 else "Fits."}
    if task["condition"] == "SUIT":
        obj.update({"risk_class_assessed": f"C{min(5, max(1, level + int(rng.integers(-1, 2))))}",
                    "suitability_check": "fixture", "conflicts_identified": []})
    return json.dumps(obj)


def test_pipeline_end_to_end(tmp_path):
    rng = np.random.default_rng(1)
    out = tmp_path / "outputs"
    raw = out / "raw"
    raw.mkdir(parents=True)
    menu = fixture_menu(tmp_path / "fund_menu.csv")
    cfg = run_experiment.load_config()
    models = run_experiment.active_models(cfg, None)
    tasks = run_experiment.plan_tasks(cfg, ["main", "consistency", "probe"], ["BASE", "SUIT"], models)
    inv = pd.read_csv(ROOT / "data" / "investor_profiles.csv").set_index("investor_id")["risk_level"]
    prb = pd.read_csv(ROOT / "data" / "probe_profiles.csv").drop_duplicates("probe_text_id")
    prb = prb.set_index("probe_text_id")["risk_level"]
    for t in tasks:
        t["risk_level"] = inv.get(t["unit_id"], prb.get(t["unit_id"]))
        rec = {k: v for k, v in t.items() if k not in ("profile_text", "risk_level")}
        rec.update({"ok": True, "content": fixture_reply(t, menu, rng),
                    "usage": {"prompt_tokens": 1500, "completion_tokens": 500}})
        with open(raw / f"calls_{t['model_key']}.jsonl", "a", encoding="utf-8") as fh:
            fh.write(json.dumps(rec) + "\n")

    code_responses.main(raw_dir=raw, menu_path=tmp_path / "fund_menu.csv", out=out)
    res = pd.read_csv(out / "experiment_results.csv")
    assert len(res) == len(tasks)
    assert (res["parse_status"] == "failed").sum() > 0          # failures are kept and flagged, not filled

    tables = analysis.run(out_root=out)
    for name in ("T04_feasibility_and_behaviour", "T09_anova_partial_eta_squared", "T13_condition_effects_paired",
                 "T14_model_comparison", "T15_consistency_repeated_queries", "T16_single_attribute_sensitivity"):
        assert len(tables[name]) > 0, name
    an = tables["T09_anova_partial_eta_squared"]
    risk = an[an["factor"] == "risk_class"]["partial_eta_sq"]
    assert (risk > 0.3).all()                                    # the fixture rule depends on risk only

    figures.make_all(out_root=out)
    pngs = sorted(p.name for p in (out / "figures").glob("*.png"))
    assert len(pngs) >= 7
